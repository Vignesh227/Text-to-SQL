    save_chat_history(user_id=user_id, memory=memory)
    # await channel.close()



    chat_history = memory.get()  

    serialized_history = [
        {"role": msg.role, "content": msg.content} for msg in chat_history
    ]

    # Extract the sql query
    generated_sql_query = serialized_history[-1]["content"] if serialized_history else None


    # CHECK IF IT IS A SQL QUERY OR A GENERAL RESPONSE
    sql_keywords = ["SELECT", "INSERT", "UPDATE", "DELETE", "CREATE", "DROP", "ALTER", "JOIN"]
    
    # Check if any SQL keyword is present anywhere in the string
