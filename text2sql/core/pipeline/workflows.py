class TextToSQLWorkflow(Workflow):
    def __init__(
            self, 
            obj_retriever, # Retrieves table schemas based on the query.
            sql_retriever, # Executes SQL queries(generated by LLM) on the database.
            sample_retriever, # Retrieves sample SQL queries related to the user's query.
            response_synthesis_prompt, # Prompt for generating the final response.
            sql_failure_prompt , # Prompt for handling SQL query failures
            sql_failure_prompt_two,
            llm, 
            text2sql_prompt, # Prompt for the text-to-SQL conversion.
            query_classification_prompt, # to classify the user question
            general_response_prompt,
            *args, 
            **kwargs
        ):
        
        super().__init__(*args, **kwargs)
        self.obj_retriever = obj_retriever
        self.sql_retriever = sql_retriever
        self.sample_retriever = sample_retriever
        self.response_synthesis_prompt = response_synthesis_prompt
        self.text2sql_prompt = text2sql_prompt
        self.sql_failure_prompt = sql_failure_prompt
        self.sql_failure_prompt_two = sql_failure_prompt_two

        self.query_classification_prompt = query_classification_prompt
        self.general_response_prompt = general_response_prompt

        # to maintain conversation history.
        self.memory = ChatMemoryBuffer.from_defaults(llm=llm) 
        self.llm = llm

    @step 
    async def new_query(self, ctx : Context, ev : StartEvent) -> ClassifyUserQuestionEvent:

        print("\n Given Input Question :", ev.query, "\n")
        
        chat_history = self.memory.get()
        ctx.write_event_to_stream(ProgressEvent(result = "Received Query"))
        
        print("Chat History: ", chat_history)

        # await ctx.set("query", ev.query)
        user_message = ChatMessage(role = "user", content = ev.query)

        self.memory.put(user_message) # Store the User Query in the memory
        
        ctx.write_event_to_stream(ProgressEvent(result = "Retrieving Table Info"))

        return ClassifyUserQuestionEvent(query=ev.query)
    
