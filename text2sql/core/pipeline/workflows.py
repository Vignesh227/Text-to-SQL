    @step
    async def classify_question(self, ctx : Context, ev : ClassifyUserQuestionEvent) -> PrepEvent | GeneralResponseEvent:

        # Retrieve and format chat history
        chat_history = self.memory.get()    
        chat_history_str = "\n".join([f"{msg.role}: {msg.content}" for msg in chat_history])

        ctx.write_event_to_stream(ProgressEvent(result = "Classifying user query (SQL Qn / General Qn)"))

        # Retrieve table schema
        table_schema_objs = await self.obj_retriever.aretrieve(ev.query)
        table_schema_objs = format_nodes_as_table_schema(table_schema_objs)
        table_context_str = get_table_context_str(table_schema_objs)

        # REtrieve sample queries
        modified_query = ev.query + "\n" + table_context_str
        sample_queries = await self.sample_retriever.aretrieve(modified_query)
        sample_query_str = "\n".join([f" - {sample.text}" for sample in sample_queries])

        fmt_messages = self.query_classification_prompt.format_messages(
            query_str = ev.query,
            schema = table_context_str,
            sample_queries = sample_query_str,
            chat_history_str = chat_history_str
        )

        classification_response = self.llm.chat(fmt_messages)
        classification_response = str(classification_response)[len("assistant: "):].strip()

        print("\n Classification Response :", classification_response, "\n")


        word = "SQL Question"

        # If SQL Query needs to be generated
        if(word in classification_response):
            iteration_number = 0
            return PrepEvent(query = ev.query, iteration_number = iteration_number)
        
        # If user asks a general question
        print("\n General question\n")

        return GeneralResponseEvent( 
            query = ev.query, 
            table_context_str = table_context_str, 
            chat_history_str = chat_history_str
        )
    



    @step
    async def generate_general_response(self, ctx : Context, ev : GeneralResponseEvent) -> StopEvent:
        
        ctx.write_event_to_stream(ProgressEvent(result = "Generating Response (for general question)"))

        fmt_messages = self.general_response_prompt.format_messages(
            query = ev.query,
            sample = ev.table_context_str,
            chat_history_str = ev.chat_history_str
        )

        chat_response = llm.chat(fmt_messages)

        # Store the generated SQL query in memory
        chat_response_str = str(chat_response)[len("assistant: "):].strip()
        self.memory.put(ChatMessage(role = "assistant", content = chat_response_str))   

        return StopEvent(result=chat_response)  


    @step
    async def retrieve_tables(self, ctx : Context, ev : PrepEvent) -> TableRetrieveEvent:

        # table_schema_objs = await self.obj_retriever.aretrieve(ev.query)
        # table_context_str = get_table_context_str(table_schema_objs)

        table_schema_objs = await self.obj_retriever.aretrieve(ev.query)
        table_schema_objs = format_nodes_as_table_schema(table_schema_objs)
        table_context_str = get_table_context_str(table_schema_objs)
        # print("Table Context: ", table_context_str)
        ctx.write_event_to_stream(ProgressEvent(result = "Analyzing Table Schema"))

        return TableRetrieveEvent(
            table_context_str = table_context_str,
            query = ev.query,
            iteration_number = ev.iteration_number
        )
    
    

    @step 
    async def retrieve_samples(self, ctx : Context, ev : TableRetrieveEvent) -> SampleRetriveEvent:

        modified_query = ev.query + "\n" + ev.table_context_str
        sample_queries = await self.sample_retriever.aretrieve(modified_query)

        sample_query_str = "\n".join([f" - {sample.text}" for sample in sample_queries])
        # print("Sample Query String : ", sample_query_str)
        # print("retreived")
        ctx.write_event_to_stream(ProgressEvent(result = "Generating SQL Query"))
        # await asyncio.sleep(0.01)
        # print("rtty")
        return SampleRetriveEvent(
            query = ev.query,
            sample_query = sample_query_str,
            table_context_str = ev.table_context_str,
            iteration_number = ev.iteration_number
        )
    


    @step 
    async def generate_sql(self, ctx : Context, ev : SampleRetriveEvent) -> Text2SQLEvent:


        # Retrieve and format chat history
        chat_history = self.memory.get()    
        chat_history_str = "\n".join([f"{msg.role}: {msg.content}" for msg in chat_history])

        fmt_messages = self.text2sql_prompt.format_messages(
            query_str=ev.query,
            schema=ev.table_context_str,
            sample_queries=ev.sample_query,
            chat_history_str = chat_history_str
        )
        
        sql = ""
        # print(fmt_messages[0].content)
        # async for sql 
        chat_response = self.llm.stream_chat(fmt_messages)
        for token in chat_response:
            sql += token.delta
            ctx.write_event_to_stream(TokenEvent(token = token.delta))

        sql = parse_response_to_sql(ChatMessage(content=sql))
        # return StopEvent(result = "Done")
        # await asyncio.sleep(0.01)
        # print("\n Generated SQL Query : ", sql)
        return Text2SQLEvent(
            sql = sql,
            query = ev.query,
            table_context_str = ev.table_context_str,
            iteration_number = ev.iteration_number
        )   



    @step 
    async def generate_sql_response(self, ctx : Context, ev : Text2SQLEvent) -> SQLFailureEvent | StopEvent:

        # print("\n Generated SQL Query : ", ev.sql)
        
        try:# Execute the generated query
            retrieved_rows = await self.sql_retriever.aretrieve(ev.sql)

        except Exception as e:
            ctx.write_event_to_stream(ProgressEvent(result = "Invalid Query Generated (retrying)"))
            return SQLFailureEvent(query = ev.query, error = str(e), sql = ev.sql,
            table_context_str = ev.table_context_str,
            iteration_number = ev.iteration_number)

        # Store the generated SQL query in memory
        self.memory.put(ChatMessage(role = "assistant", content = ev.sql))   

        print("\n Generated SQL Query : ", ev.sql)
        
        ctx.write_event_to_stream(ProgressEvent(result = "Generating Response (SQL based Question)"))

        chat_history = self.memory.get()
        chat_history_str = "\n".join([f"{msg.role}: {msg.content}" for msg in chat_history])

        print("\n Chat History : ", chat_history, "\n")

        fmt_messages = self.response_synthesis_prompt.format_messages(
            sql_query = ev.sql,
            context_str = str(retrieved_rows),
            query_str = ev.query,
            chat_history_str = chat_history_str
        )

        # print("\n Formatted Messages : ", fmt_messages, "\n")

        # print('\n Formatted Message : ',fmt_messages)
        
        chat_response = llm.chat(fmt_messages)
        return StopEvent(result=chat_response)


    
    @step
    async def handle_sql_failure(self, ctx : Context, ev : SQLFailureEvent) -> StopEvent:

        ev.iteration_number = ev.iteration_number + 1

        if ev.iteration_number < 4:
            chat_history = self.memory.get()
            chat_history_str = "\n".join([f"{msg.role}: {msg.content}" for msg in chat_history])

            fmt_messages = self.sql_failure_prompt.format_messages(
                query_str = ev.query,
                sql_query_str = ev.sql,
                error = ev.error,
                chat_history_str = chat_history_str,
                table_context_str = ev.table_context_str
            )

            # print(fmt_messages)
            chat_response = self.llm.chat(fmt_messages)
            # print(type(chat_response))
            sql = parse_response_to_sql(chat_response)
            
            return Text2SQLEvent(
                sql = sql,
                query = ev.query,
                table_context_str = ev.table_context_str,
                iteration_number = ev.iteration_number
            )

        else:
            chat_history = self.memory.get()
            chat_history_str = "\n".join([f"{msg.role}: {msg.content}" for msg in chat_history])

            fmt_messages = self.sql_failure_prompt_two.format_messages(
                query_str = ev.query,
                sql_query_str = ev.sql,
                error = ev.error,
                chat_history_str = chat_history_str,
                table_context_str = ev.table_context_str
            )

            # print(fmt_messages)
            chat_response = self.llm.chat(fmt_messages)

            # Store the generated response in memory
            chat_response_str = str(chat_response)[len("assistant: "):].strip()
            self.memory.put(ChatMessage(role = "assistant", content = chat_response_str))   

            return StopEvent(result=chat_response)



